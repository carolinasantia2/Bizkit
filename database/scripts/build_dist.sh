#!/usr/bin/env bash
# ---------- Build dist/ ----------
# Assembles the two graded files from the per-table and per-cluster
# source files, in dependency order:
#   dist/01_create_schema.sql      <- CREATE DATABASE + drops + every CREATE TABLE and index
#   dist/02_insert_seed_data.sql   <- every INSERT
#
# Run from anywhere (macOS Terminal, Linux, or Git Bash on Windows):
#   bash database/scripts/build_dist.sh
#
# dist/ is generated output. Never edit it by hand: fix the source file
# under src/ or scripts/, then rerun this script.
set -euo pipefail

# Work from database/ so every path below is relative to it.
cd "$(dirname "$0")/.."

DB_NAME="bizkit"

# Explicit create order, parents first (see the dependency levels in the
# README). NOT alphabetical. When you add a table, add it here AND add its
# DROP to scripts/pre-deployment/drop_all_objects.sql.
TABLES=(
  "01_foundation/ServiceArea.sql"
  "01_foundation/Course.sql"
  "01_foundation/Employee.sql"
  "01_foundation/DiningTable.sql"
  "01_foundation/Server.sql"
  "01_foundation/Manager.sql"
  "01_foundation/Shift.sql"
  "02_menu/MenuEntry.sql"
  "02_menu/Category.sql"
  "02_menu/MenuItem.sql"
  "02_menu/AddOn.sql"
  # Tolu (#12): uncomment when the files exist
  # "03_checks_orders/GuestCheck.sql"
  # "03_checks_orders/OrderItem.sql"
  # "03_checks_orders/OrderItemAddOn.sql"
  # "04_floor_operations/ItemTransfer.sql"
  # Vigneshwar (#13): uncomment when the files exist
  # "05_payments/Payment.sql"
  # "05_payments/CardPayment.sql"
  # "05_payments/CashPayment.sql"
  # "06_shift_close/ShiftCarryover.sql"
)

# Indexes, triggers and views run after every table exists.
OBJECTS=(
  "indexes/UX_MenuEntry_SingleRoot.sql"
  "indexes/UX_Shift_SingleOpen.sql"
)

# Seed order, parents first.
SEEDS=(
  "foundation_data.sql"
  "menu_data.sql"
  # Tolu (#12):       "checks_orders_data.sql"
  # Vigneshwar (#13): "payments_data.sql"
)

DROP_SCRIPT="scripts/pre-deployment/drop_all_objects.sql"
CREATE_OUT="dist/01_create_schema.sql"
INSERT_OUT="dist/02_insert_seed_data.sql"

# Fail early if any source file is missing.
missing=0
for f in "$DROP_SCRIPT" "${TABLES[@]/#/src/tables/}" "${OBJECTS[@]/#/src/}" "${SEEDS[@]/#/scripts/post-deployment/}"; do
  if [[ ! -f "$f" ]]; then echo "Missing: database/$f" >&2; missing=1; fi
done
[[ $missing -eq 0 ]] || { echo "Build stopped. Nothing was written." >&2; exit 1; }

# Print a source file with its label, followed by GO. Strips a UTF-8
# byte-order mark and Windows line endings (some editors save them, and
# either breaks a combined file). The $'...' quoting and LC_ALL=C make
# this work with both macOS (BSD) sed and GNU sed.
emit() {
  echo
  echo "-- =================================================================="
  echo "-- Source: database/$1"
  echo "-- =================================================================="
  LC_ALL=C sed -e $'1s/^\xEF\xBB\xBF//' -e $'s/\r$//' "$1"
  echo
  echo "GO"
}

mkdir -p dist

{
  echo "-- ---------- 01_create_schema.sql ----------"
  echo "-- GENERATED by database/scripts/build_dist.sh. Do not edit by hand."
  echo "-- Creates the database if needed, drops every object (children first),"
  echo "-- then creates all tables and indexes in dependency order. Safe to rerun."
  echo
  echo "USE master;"
  echo "GO"
  echo
  echo "IF DB_ID(N'$DB_NAME') IS NULL"
  echo "    CREATE DATABASE $DB_NAME;"
  echo "GO"
  echo
  echo "USE $DB_NAME;"
  echo "GO"
  emit "$DROP_SCRIPT"
  for t in "${TABLES[@]}"; do emit "src/tables/$t"; done
  for o in "${OBJECTS[@]}"; do emit "src/$o"; done
} > "$CREATE_OUT"

{
  echo "-- ---------- 02_insert_seed_data.sql ----------"
  echo "-- GENERATED by database/scripts/build_dist.sh. Do not edit by hand."
  echo "-- Run AFTER 01_create_schema.sql. Hardcoded IDs assume freshly created tables."
  echo
  echo "USE $DB_NAME;"
  echo "GO"
  echo
  echo "-- Guard: refuse to run against tables that already hold data, since"
  echo "-- the hardcoded IDs would collide. SET NOEXEC ON skips every remaining"
  echo "-- batch; it's switched back off at the end."
  echo "IF EXISTS (SELECT 1 FROM dbo.SERVICE_AREA)"
  echo "BEGIN"
  echo "    RAISERROR('Tables already contain data. Run 01_create_schema.sql first, then rerun this script.', 16, 1);"
  echo "    SET NOEXEC ON;"
  echo "END"
  echo "GO"
  for s in "${SEEDS[@]}"; do emit "scripts/post-deployment/$s"; done
  echo
  echo "SET NOEXEC OFF;"
  echo "GO"
} > "$INSERT_OUT"

echo "Built database/$CREATE_OUT ($(grep -c '^CREATE TABLE' "$CREATE_OUT") CREATE TABLE statements)"
echo "Built database/$INSERT_OUT ($(grep -c '^INSERT INTO' "$INSERT_OUT") INSERT statements)"